// Token Radar's model, version radar-2.
//
// One snapshot of the protocol universe in, one ranked board out. The board ranks every rankable
// pre-token protocol the snapshot records: the whole watchlist (the floor) plus every other
// pre-token protocol that is not a wrapped, staked or bridged product of a token that already
// trades. Protocols whose token already trades are kept apart and shown with the market's own
// value, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. The one idea this model adds over a
// flat multiple is that the market already prices launches: the live-token protocols in the snapshot
// carry both a market cap and a TVL, so each category's own median market-cap-to-TVL ratio is the
// multiple its pre-token protocols are scored with. A category with too few live comparables falls
// back to the whole snapshot's median. No protocol name is ever special-cased: the same function
// scores every row, and the per-row breakdown names the multiple it used and where it came from.
//
//   multiple     = median(mcap_usd / tvl_usd) over the category's live comparables, or the
//                    snapshot-wide median when the category has fewer than 3; clamped to
//                    [MULTIPLE_FLOOR, MULTIPLE_CAP]
//   base         = tvl_usd x multiple
//   growth       = clamp(change_7d, -60, 120) per cent; growthMult = 1 + (growth / 100) x 0.5
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth      = 1 + 0.02 x min(chains, 5)
//   implied      = max(1, round(base x growthMult x maturity x breadth))
//
// The dashboard recomputes every row from the same figures, so the page and board.json agree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and its sandbox may change them. */
